def one(m):
    d = {c.split("_", 1)[0]: c.split("_", 1)[1] for c in m["conds"] if c.split("_", 1)[0] in ("TS", "TEMPO", "MODE", "DENS", "POLY", "REG", "VEL", "SWING")}
    fams = []
    for c in m["conds"]:
        if not c.startswith("FAM_"): continue
        f = c[4:]; only = m.get("only", {}).get(f)
        names = sorted({PROG.get(p, "") for p in only} - {""}) if only else []
        fams.append(FAM.get(f, f) + (f"({'·'.join(names)})" if names else ""))
    bias = m.get("bias", {})
    up = [FAM.get(f, f) for f, v in sorted(bias.items(), key=lambda x: -x[1]) if v > 0]
    down = [FAM.get(f, f) for f, v in sorted(bias.items(), key=lambda x: x[1]) if v < 0]
    moods = [c[5:] for c in m["conds"] if c.startswith("MOOD_")]
    L = [f"### {m['emoji']} {m['name']}", f"- 한 줄로: {' · '.join(m['say'])}",
         f"- 빠르기: {TEMPO[int(d['TEMPO'])]} BPM · 박자 {d['TS']}" + (f" · 리듬 {SW[int(d['SWING'])]}" if 'SWING' in d else ""),
         f"- 조: {'장조' if d['MODE'] == 'major' else '단조'} · 음 밀도: {DENS[int(d['DENS'])]} · 겹친 음: {POLY[int(d['POLY'])]} · 음역: {REG[int(d['REG'])]} · 세기: {VEL[int(d['VEL'])]}",
         f"- 악기: {', '.join(fams)} · 드럼 소리: {KIT[m['kit']]}"]
    if up or down:
        L.append("- 악기 무게: " + " · ".join(([f"더 자주 {', '.join(up)}"] if up else []) + ([f"덜 {', '.join(down)}"] if down else [])))
    TUNE = {"+melodic": "분위기 꼬리표 melodic 추가", "+ballad": "꼬리표 ballad 추가", "-ballad": "꼬리표 ballad 뺌",
            "DENS-1": "음 밀도 한 칸 낮춤", "POLY-1": "겹친 음 한 칸 줄임", "temp+0.1": "창의성 +0.1"}
    if m.get("temp") and abs(m["temp"] - 0.9) > 1e-6:
        L.append(f"- 창의성(온도): {m['temp']:.2f}")
    if m.get("tuned"):
        L.append(f"- 자동 탐색(후보 설정 × 시드 3개 점수)으로 고친 점: {TUNE.get(m['tuned'], m['tuned'])}")
    L += [f"- 분위기 꼬리표(학습 데이터 MidiCaps 기준): {', '.join(moods)}", f"- 볼륨: {m['vol']:+d} dB",
          f"- 코드 진행 {len(m['progs'])}가지를 돌려 씀 (조 {len(m['keys'])}곳 사이를 가까운 조로 옮겨 감)"]
    return "\n".join(L)


